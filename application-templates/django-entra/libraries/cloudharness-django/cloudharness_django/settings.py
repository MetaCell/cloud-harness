import os
from django.conf import settings
from django.core.exceptions import ImproperlyConfigured


# ***********************************************************************
# * CloudHarness Django settings
# ***********************************************************************
from cloudharness import applications, log
from cloudharness.utils.config import CloudharnessConfig as conf

# add the local apps
INSTALLED_APPS = getattr(
    settings,
    'INSTALLED_APPS',
    []) + ['cloudharness_django', 'django_prometheus']

# add the Entra bearer token and login required middlewares
MIDDLEWARE = \
    ['django_prometheus.middleware.PrometheusBeforeMiddleware'] + \
    getattr(
        settings,
        'MIDDLEWARE',
        []
    ) + \
    [
        'cloudharness_django.middleware.BearerTokenMiddleware',
        'cloudharness_django.middleware.LoginRequiredMiddleware',
        'django_prometheus.middleware.PrometheusAfterMiddleware'
    ]

# Entra users log in through OIDC. The password login of local users (e.g. created with createsuperuser)
# bypasses Entra (MFA, conditional access): by default only in local development (DEBUG on)
PASSWORD_LOGIN_ENABLED = getattr(settings, 'PASSWORD_LOGIN_ENABLED', getattr(settings, 'DEBUG', False))
AUTHENTICATION_BACKENDS = ['cloudharness_django.backends.EntraBackend'] + \
    (['django.contrib.auth.backends.ModelBackend'] if PASSWORD_LOGIN_ENABLED else [])
LOGIN_URL = '/oidc/login/'
LOGIN_REDIRECT_URL = '/'

USER_CHANGE_ENABLED = False

SECRET_KEY_NAME = "django-secret-key"
# local development only: never used with DEBUG off
DEVELOPMENT_SECRET_KEY = "django-insecure-development-only"


def _get_secret_key():
    """DJANGO_SECRET_KEY, else the `django-secret-key` application secret (generated by CloudHarness)."""
    if os.getenv("DJANGO_SECRET_KEY"):
        return os.getenv("DJANGO_SECRET_KEY")
    try:
        from cloudharness.utils.secrets import get_secret
        return get_secret(SECRET_KEY_NAME).strip() or None
    except Exception:
        return None


SECRET_KEY = _get_secret_key()
if not SECRET_KEY:
    if not getattr(settings, "DEBUG", False):
        raise ImproperlyConfigured(
            f"No Django secret key: set the `{SECRET_KEY_NAME}` application secret or DJANGO_SECRET_KEY")
    SECRET_KEY = DEVELOPMENT_SECRET_KEY

# get the application CH config
app_name = settings.PROJECT_NAME.lower()
try:
    current_app = applications.get_current_configuration()

    # behind the ingress controller: trust the forwarded host and protocol
    # so that the OIDC redirect uri is built with the public address
    USE_X_FORWARDED_HOST = True
    SECURE_PROXY_SSL_HEADER = ("HTTP_X_FORWARDED_PROTO", "https")

    # only the public host names of the application and its in-cluster service names are accepted
    # (Host and X-Forwarded-Host), plus the pod ip used by the Kubernetes probes (POD_IP)
    _harness = current_app.harness
    _service = _harness.service.name
    _namespace = conf.get_namespace()
    ALLOWED_HOSTS = getattr(settings, "ALLOWED_HOSTS", []) + [
        f"{subdomain}.{conf.get_domain()}" for subdomain in [_harness.subdomain] + list(getattr(_harness, "aliases", None) or [])
    ] + ([_harness.domain] if getattr(_harness, "domain", None) else []) + [
        _service, f"{_service}.{_namespace}", f"{_service}.{_namespace}.svc", f"{_service}.{_namespace}.svc.cluster.local",
    ] + ([os.environ["POD_IP"]] if os.getenv("POD_IP") else [])

    # https only cookies when the deployment is served on https
    if conf.get_configuration().get("tls"):
        SESSION_COOKIE_SECURE = True
        CSRF_COOKIE_SECURE = True

    # CSRF, set CSRF_TRUSTED_ORIGINS
    CH_DOMAIN = conf.get_domain()
    CSRF_TRUSTED_ORIGINS = getattr(
        settings,
        'CSRF_TRUSTED_ORIGINS',
        []) + [f"https://{CH_DOMAIN}", f"https://*.{CH_DOMAIN}"]
except:
    # no current app found, fall back to the default settings, there is a good chance that
    # we are running on a developers local machine
    log.warning("Error setting current app configuration, was `harness-deployment` executed? Continuing...")

    current_app = applications.ApplicationConfiguration({
        "name": app_name,
        "harness": {
            "database": {
                "name": app_name,
                "type": "sqlite3",
                "host": None,
            }
        }
    })
    ALLOWED_HOSTS = getattr(settings, "ALLOWED_HOSTS", []) + ["localhost", "127.0.0.1", "[::1]"]
    # CSRF
    CSRF_TRUSTED_ORIGINS = ["http://localhost:8000", "http://localhost:8080"]

if current_app.harness.database.type == "sqlite3":
    DATABASE_ENGINE = "django.db.backends.sqlite3"
    DATABASE_NAME = os.path.join(getattr(settings, "PERSISTENT_ROOT", "."), f"{app_name}.sqlite3")
    DATABASE_HOST = None
    DATABASE_PORT = None
    TEST_DATABASE_NAME = ":memory:"
elif current_app.harness.database.type == "postgres":
    DATABASE_ENGINE = "django.db.backends.postgresql"
    DATABASE_NAME = current_app.harness.database.postgres.initialdb
    TEST_DATABASE_NAME = f"test_{DATABASE_NAME}"
    DATABASE_HOST = current_app.harness.database.name
    DATABASE_PORT = current_app.harness.database.postgres.ports[0].port

# Database
# https://docs.djangoproject.com/en/5.0/ref/settings/#databases
DATABASES = {
    "default": {
        "ENGINE": DATABASE_ENGINE,
        "NAME": DATABASE_NAME,
        "USER": getattr(current_app.harness.database, "user", None),
        "PASSWORD": getattr(current_app.harness.database, "pass", None),
        "HOST": DATABASE_HOST,
        "PORT": DATABASE_PORT,
        "CONN_MAX_AGE": 600,  # Connection persistent timeouts in seconds (default 0 = close after each request)
        "TEST": {
            "ENGINE": DATABASE_ENGINE or "django.db.backends.sqlite3",
            "NAME": TEST_DATABASE_NAME,
        },
    },
}

if settings.ROOT_URLCONF:
    APP_URLCONF = settings.ROOT_URLCONF
    ROOT_URLCONF = "cloudharness_django.urls"
