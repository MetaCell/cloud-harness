#!/usr/bin/env python3
"""Repoint every docker image used by a CloudHarness checkout from one configuration file.

Two modes:

  scan   List every image used in a configuration file, with the file/line of each use
         and an empty `replace_with` placeholder. Two scopes:
           deployment (default)  the artifacts generated by `harness-deployment`: the helm
                                 chart and the other files under deployment/, skaffold.yaml,
                                 Tiltfile, plus the Dockerfiles the builds read. Edit these
                                 right before deploying.
           sources               the CloudHarness sources (applications, infrastructure,
                                 deployment-configuration templates...), for permanent changes.
         Images CloudHarness builds itself are left out. If deployment/helm/values-overrides.yaml
         exists, its helm paths are attached to the entries.

  apply  Read the configuration back and, for every entry whose `replace_with` has been
         filled with a different image, rewrite each listed use in place. Formatting,
         quoting and comments are preserved; split image fields (name/tag,
         registry/repository/tag, image/imageTag) are rewritten field by field.

Usage:
  python ch_images.py scan  --root ~/cloud-harness [--scope deployment|sources] [--config ch-images.yaml]
  python ch_images.py apply --root ~/cloud-harness [--config ch-images.yaml] [--dry-run]
  python ch_images.py help                         full guide: workflow, config format, tips

Only dependency: PyYAML (pip install -r requirements.txt).
"""
import argparse
import dataclasses
import datetime
import difflib
import fnmatch
import os
import re
import subprocess
import sys
from typing import Optional

import yaml
from yaml.nodes import MappingNode, ScalarNode, SequenceNode

DEFAULT_CONFIG = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ch-images.yaml")
OVERRIDES_FILE = "deployment/helm/values-overrides.yaml"

HELM_VALUES = "deployment/helm/values.yaml"
SKAFFOLD = "skaffold.yaml"
TILTFILE = "Tiltfile"
DOCKERFILES = ["Dockerfile", "*/Dockerfile", "*/Dockerfile.*", "*.Dockerfile"]
# Generated by harness-deployment (ignored by git, so collected explicitly)
GENERATED = ["deployment/*", SKAFFOLD, TILTFILE]

SCOPES = {
    "deployment": {
        "includes": GENERATED + DOCKERFILES,
        # values-overrides.yaml is the reference the helm paths are read from, not an input of the chart
        "excludes": [OVERRIDES_FILE, "*/node_modules/*", "*values.schema.yaml"],
    },
    "sources": {
        "includes": ["*"],
        "excludes": GENERATED + ["*/node_modules/*", "*values.schema.yaml"],
    },
}
TEST_EXCLUDES = [
    "*/tests/*",
    "*/test/resources/*",
]
SKIP_DIRS = {".git", "node_modules", "venv", ".venv", "__pycache__", ".tox", ".mypy_cache"}

# A docker image reference: [registry[:port]/]path[:tag][@digest]
REF_RE = re.compile(
    r"^(?:[A-Za-z0-9.-]+(?::\d+)?/)?"
    r"[a-z0-9]+(?:(?:[._]|__|-+)[a-z0-9]+)*"
    r"(?:/[a-z0-9]+(?:(?:[._]|__|-+)[a-z0-9]+)*)*"
    r"(?::[\w][\w.-]{0,127})?"
    r"(?:@sha256:[0-9a-f]{64})?$"
)
IMAGE_KEY_RE = re.compile(r"^(?:image|[a-z][A-Za-z0-9]*Image)$")
SOURCE_IMAGES_KEY = "source_images"
EXAMPLE_KEYS = {"example", "examples"}  # OpenAPI / JSON schema examples
YAML_LINE_RE = re.compile(
    r"^(?P<pre>\s*(?:-\s+)?(?:image|[a-z][A-Za-z0-9]*Image)\s*:\s*)"
    r"(?P<q>[\"']?)(?P<val>[^\"'\s#]+)(?P=q)\s*(?:#.*)?$"
)
FROM_RE = re.compile(r"^\s*FROM\s+(?:--\S+\s+)*(?P<img>\S+)(?:\s+AS\s+(?P<stage>\S+))?", re.I)
ARG_RE = re.compile(r"^\s*ARG\s+(?P<name>\w+)=(?P<q>[\"']?)(?P<val>[^\"'\s]+)(?P=q)", re.I)
COPY_FROM_RE = re.compile(r"--from=(?P<img>[^\s]+)", re.I)
VAR_RE = re.compile(r"^\$\{?(\w+)\}?$")


# --------------------------------------------------------------------------- model

@dataclasses.dataclass
class Field:
    """One editable span of a file holding (part of) an image reference."""
    role: str           # full | name | repository | registry | tag
    line: int           # 0-based
    start: int
    end: int
    value: str
    style: Optional[str] = None   # None (plain), "'" or '"'; only for YAML scalars
    insert_at: Optional[int] = None  # for empty YAML values: column right after the ':'


@dataclasses.dataclass
class Occurrence:
    file: str
    kind: str           # dockerfile-from | dockerfile-arg | dockerfile-copy-from | yaml | yaml-split | yaml-line | text
    path: str
    fields: list

    @property
    def line(self) -> int:
        return min(f.line for f in self.fields) + 1

    @property
    def image(self) -> str:
        return compose_image(self.fields)


class ConfigError(Exception):
    pass


# --------------------------------------------------------------------------- image refs

def is_image(value) -> bool:
    if not isinstance(value, str) or not value or "{{" in value or "$" in value:
        return False
    if value.lower() in ("true", "false", "null", "none", "always", "ifnotpresent", "never"):
        return False
    if value.replace(".", "").isdigit():
        return False
    return bool(REF_RE.match(value))


def parse_ref(ref: str) -> dict:
    digest = None
    if "@" in ref:
        ref, digest = ref.split("@", 1)
    tag = None
    if ":" in ref.rsplit("/", 1)[-1]:
        ref, tag = ref.rsplit(":", 1)
    registry, repository = None, ref
    first, _, rest = ref.partition("/")
    if rest and ("." in first or ":" in first or first == "localhost"):
        registry, repository = first, rest
    return {"registry": registry, "repository": repository, "tag": tag, "digest": digest}


def strip_tag(ref: str) -> str:
    p = parse_ref(ref)
    return f"{p['registry']}/{p['repository']}" if p["registry"] else p["repository"]


def compose_image(fields) -> str:
    by_role = {f.role: f.value for f in fields}
    if "full" in by_role:
        return by_role["full"]
    name = by_role.get("name") or by_role.get("repository") or ""
    if by_role.get("registry"):
        name = f"{by_role['registry']}/{name}"
    tag = by_role.get("tag")
    if tag:
        name += tag if tag.startswith("@") else f":{tag}"
    return name


def split_new_image(new: str, roles) -> dict:
    """Values for each split field of an occurrence, from a full new image reference."""
    p = parse_ref(new)
    tag = p["tag"] or ""
    if p["digest"]:
        tag = f"{tag}@{p['digest']}" if tag else f"@{p['digest']}"
    if "tag" in roles and not tag:
        raise ConfigError(f"'{new}' has no tag, but this location keeps the tag in its own field")
    if "tag" not in roles and tag:
        raise ConfigError(f"'{new}' has a tag, but this location has no tag field")
    out = {}
    if "registry" in roles:
        out["registry"] = p["registry"] or "docker.io"
        out["repository"] = p["repository"]
    else:
        key = "name" if "name" in roles else "repository"
        out[key] = strip_tag(new.split("@", 1)[0])
    if "tag" in roles:
        out["tag"] = tag
    return out


# --------------------------------------------------------------------------- file discovery

def list_files(root: str, includes, excludes) -> list:
    try:
        out = subprocess.run(
            ["git", "ls-files", "-co", "--exclude-standard"],
            cwd=root, capture_output=True, text=True, check=True,
        ).stdout.splitlines()
    except (OSError, subprocess.CalledProcessError):
        out = walk(root, ".")
    # the harness-deployment artifacts are git-ignored
    out += walk(root, "deployment") + [f for f in (SKAFFOLD, TILTFILE) if os.path.isfile(os.path.join(root, f))]
    files = []
    for rel in sorted(set(out)):
        rel = rel.replace(os.sep, "/")
        if not any(fnmatch.fnmatch(rel, pat) for pat in includes):
            continue
        if any(fnmatch.fnmatch(rel, pat) for pat in excludes):
            continue
        if not os.path.isfile(os.path.join(root, rel)):
            continue
        if is_dockerfile(rel) or is_yaml(rel) or is_text_only(rel):
            files.append(rel)
    return files


def walk(root: str, sub: str) -> list:
    out = []
    for dirpath, dirnames, filenames in os.walk(os.path.join(root, sub)):
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS]
        for fn in filenames:
            out.append(os.path.relpath(os.path.join(dirpath, fn), root))
    return out


def is_text_only(rel: str) -> bool:
    """Files only searched for literal uses of the images found elsewhere."""
    return rel.endswith(".tpl") or os.path.basename(rel) == TILTFILE


def is_dockerfile(rel: str) -> bool:
    base = os.path.basename(rel).lower()
    return base == "dockerfile" or base.startswith("dockerfile.") or base.endswith(".dockerfile")


def is_yaml(rel: str) -> bool:
    return rel.lower().endswith((".yaml", ".yml"))


def read_lines(root: str, rel: str) -> list:
    with open(os.path.join(root, rel), encoding="utf-8", errors="surrogateescape") as f:
        return f.read().split("\n")


# --------------------------------------------------------------------------- Dockerfile scan

def scan_dockerfile(rel: str, lines) -> list:
    occs = []
    stages = set()
    args = {}          # name -> Field
    used_args = set()

    def ref_or_var(img, line_no, col, kind, path):
        m = VAR_RE.match(img)
        if m:
            used_args.add(m.group(1))
        elif img.lower() not in stages and img != "scratch" and is_image(img):
            occs.append(Occurrence(rel, kind, path, [Field("full", line_no, col, col + len(img), img)]))

    for i, line in enumerate(lines):
        m = ARG_RE.match(line)
        if m and is_image(m.group("val")):
            args[m.group("name")] = Field("full", i, m.start("val"), m.end("val"), m.group("val"))
            continue
        m = FROM_RE.match(line)
        if m:
            ref_or_var(m.group("img"), i, m.start("img"), "dockerfile-from", "FROM")
            if m.group("stage"):
                stages.add(m.group("stage").lower())
            continue
        if re.match(r"^\s*COPY\s", line, re.I):
            m = COPY_FROM_RE.search(line)
            if m and not m.group("img").isdigit():
                ref_or_var(m.group("img"), i, m.start("img"), "dockerfile-copy-from", "COPY --from")

    for name, field in args.items():
        if name in used_args:
            occs.append(Occurrence(rel, "dockerfile-arg", f"ARG {name}", [field]))
    return occs


# --------------------------------------------------------------------------- YAML scan

def scalar_field(role, node: ScalarNode, key: ScalarNode, lines) -> Optional[Field]:
    if node.start_mark.line != node.end_mark.line and node.value:
        return None  # multi-line scalar, not an image
    if node.value == "" and node.style is None:
        # empty value: insert right after "key:" on the key's line
        kl, kc = key.end_mark.line, key.end_mark.column
        colon = lines[kl].find(":", kc)
        if colon < 0:
            return None
        return Field(role, kl, colon + 1, colon + 1, "", None, insert_at=colon + 1)
    return Field(role, node.start_mark.line, node.start_mark.column, node.end_mark.column,
                 node.value, node.style if node.style in ("'", '"') else None)


def walk_yaml(rel, node, path, lines, occs, seen):
    if isinstance(node, SequenceNode):
        for i, item in enumerate(node.value):
            walk_yaml(rel, item, path + [f"[{i}]"], lines, occs, seen)
        return
    if not isinstance(node, MappingNode):
        return
    items = [(k, v) for k, v in node.value if isinstance(k, ScalarNode)]
    keys = {k.value: (k, v) for k, v in items}
    in_source_images = bool(path) and path[-1] == SOURCE_IMAGES_KEY
    for k, v in items:
        p = path + [k.value]
        dotted = ".".join(p).replace(".[", "[")
        if id(v) in seen or k.value in EXAMPLE_KEYS:
            continue
        if isinstance(v, ScalarNode) and (IMAGE_KEY_RE.match(k.value) or in_source_images):
            if not is_image(v.value):
                continue
            seen.add(id(v))
            f = scalar_field("full", v, k, lines)
            if not f:
                continue
            tag_kv = keys.get(f"{k.value}Tag")
            if tag_kv and isinstance(tag_kv[1], ScalarNode) and parse_ref(v.value)["tag"] is None:
                tf = scalar_field("tag", tag_kv[1], tag_kv[0], lines)
                if tf:
                    seen.add(id(tag_kv[1]))
                    f.role = "name"
                    occs.append(Occurrence(rel, "yaml-split", dotted, [f, tf]))
                    continue
            occs.append(Occurrence(rel, "yaml", dotted, [f]))
            continue
        if isinstance(v, MappingNode) and IMAGE_KEY_RE.match(k.value):
            sub = {sk.value: (sk, sv) for sk, sv in v.value if isinstance(sk, ScalarNode)}
            name_key = "name" if "name" in sub else "repository" if "repository" in sub else None
            if name_key and isinstance(sub[name_key][1], ScalarNode):
                fields = []
                for role in ("registry", name_key, "tag"):
                    if role in sub and isinstance(sub[role][1], ScalarNode):
                        sk, sv = sub[role]
                        if role != "tag" and sv.value and not re.match(r"^[\w./:-]+$", sv.value):
                            fields = []
                            break
                        f = scalar_field(role, sv, sk, lines)
                        if f:
                            fields.append(f)
                if fields and is_image(compose_image(fields)):
                    seen.add(id(v))
                    occs.append(Occurrence(rel, "yaml-split", dotted, fields))
                    continue
        walk_yaml(rel, v, p, lines, occs, seen)


def scan_yaml_lines(rel, lines) -> list:
    """Fallback for files that are not valid YAML (helm templates)."""
    occs = []
    for i, line in enumerate(lines):
        if "{{" in line:
            continue
        m = YAML_LINE_RE.match(line)
        if m and is_image(m.group("val")):
            key = m.group("pre").strip().lstrip("-").strip().rstrip(":").strip()
            occs.append(Occurrence(rel, "yaml-line", key, [
                Field("full", i, m.start("val"), m.end("val"), m.group("val"), m.group("q") or None)]))
    return occs


def scan_yaml(rel, lines, root=None) -> list:
    text = "\n".join(lines)
    try:
        docs = list(yaml.compose_all(text, Loader=yaml.SafeLoader))
    except yaml.YAMLError:
        return scan_yaml_lines(rel, lines)
    occs, seen = [], set()
    prefix = subchart_key(root, rel) if root else None
    for doc in docs:
        if doc is not None:
            walk_yaml(rel, doc, [prefix] if prefix else [], lines, occs, seen)
    return occs


def subchart_key(root, rel):
    """Values of a vendored sub-chart are read by Helm under the `name` of its own Chart.yaml
    (argo -> argo-workflows): prefix their paths so they read like values-overrides.yaml."""
    if "/charts/" not in rel or os.path.basename(rel) != "values.yaml":
        return None
    chart = os.path.join(root, os.path.dirname(rel), "Chart.yaml")
    if not os.path.isfile(chart):
        return None
    with open(chart, encoding="utf-8") as f:
        return (yaml.safe_load(f) or {}).get("name")


def scan(root, includes, excludes, extra_images=(), built=frozenset()) -> list:
    """Structured scan of Dockerfiles and YAML, then a literal pass for every image found
    (plus `extra_images`) to catch the uses no structure reveals: helm template defaults,
    build arguments in skaffold.yaml / Tiltfile / codefresh, docker-compose templates..."""
    occs = []
    contents = {}
    for rel in list_files(root, includes, excludes):
        lines = contents[rel] = read_lines(root, rel)
        if is_dockerfile(rel):
            occs += scan_dockerfile(rel, lines)
        elif is_yaml(rel):
            occs += scan_yaml(rel, lines, root)
    occs = [o for o in occs if not is_built(o.image, built)]
    images = {o.image for o in occs} | set(extra_images)
    occs += search_literal(contents, images, occs)
    return occs


def built_images(root, pulled) -> set:
    """Images CloudHarness builds itself, read from the generated chart and skaffold.yaml.
    They are no image source to repoint. `pulled` (e.g. what values-overrides.yaml lists, which
    includes the prebuilt images of `build: false` applications) is never considered built."""
    names = set()

    def load(rel):
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            return {}
        with open(path, encoding="utf-8") as f:
            return yaml.safe_load(f) or {}

    values = load(HELM_VALUES)
    for key in ("task-images", "test-images"):
        names.update((values.get(key) or {}).values())
    for app in (values.get("apps") or {}).values():
        if not isinstance(app, dict):
            continue
        names.add(app.get("image"))
        names.update((app.get("task-images") or {}).values())
        names.add(((app.get("harness") or {}).get("deployment") or {}).get("image"))
    for artifact in ((load(SKAFFOLD).get("build") or {}).get("artifacts") or []):
        names.add(artifact.get("image"))
    for rel in walk(root, "deployment"):
        if os.path.basename(rel).startswith("codefresh") and is_yaml(rel):
            names.update(re.findall(r"^\s*image_name:\s*['\"]?([^'\"\s]+)", "\n".join(read_lines(root, rel)), re.M))
    pulled = {strip_tag(p) for p in pulled if p}
    return {strip_tag(n) for n in names if isinstance(n, str) and n} - pulled


def is_built(image, built) -> bool:
    name = strip_tag(image)
    return any(name == b or name.endswith("/" + b) for b in built)


# --------------------------------------------------------------------------- values-overrides

def overrides_images(root, overrides_rel) -> list:
    path = os.path.join(root, overrides_rel)
    if not os.path.isfile(path):
        return []
    lines = read_lines(root, overrides_rel)
    occs, seen = [], set()
    for doc in yaml.compose_all("\n".join(lines), Loader=yaml.SafeLoader):
        if doc is not None:
            walk_yaml(overrides_rel, doc, [], lines, occs, seen)
    return occs


def overrides_stale(root, overrides_rel, occs) -> bool:
    mtime = os.path.getmtime(os.path.join(root, overrides_rel))
    return any(os.path.getmtime(os.path.join(root, f)) > mtime + 1 for f in {o.file for o in occs})


def search_literal(contents, images, structured) -> list:
    """Literal uses of known images not already covered by a structured occurrence.
    Single-word images (alpine, postgres) are left out: they match ordinary prose too."""
    images = sorted((i for i in images if i and ("/" in i or ":" in i)), key=len, reverse=True)
    if not images:
        return []
    pattern = re.compile(r"(?<![\w./:@-])(?:" + "|".join(map(re.escape, images)) + r")(?![\w./:@-])")
    covered = {}
    for o in structured:
        for f in o.fields:
            covered.setdefault((o.file, f.line), []).append((f.start, f.end))
    hits = []
    for rel, lines in contents.items():
        for i, line in enumerate(lines):
            for m in pattern.finditer(line):
                spans = covered.get((rel, i), [])
                if any(a < m.end() and m.start() < b for a, b in spans):
                    continue
                hits.append(Occurrence(rel, "text", "", [Field("full", i, m.start(), m.end(), m.group(0))]))
    return hits


# --------------------------------------------------------------------------- config

CONFIG_HEADER = """\
# Docker images of a CloudHarness checkout, generated by `ch_images.py scan --scope {scope}`.
#
# For each image you want to change, fill `replace_with` with the full new reference
# (e.g. myregistry.io/mirror/python:3.12-slim-trixie), then run:
#
#   python ch_images.py apply --config {config} [--dry-run]
#
# - Empty `replace_with` (or equal to `image`) leaves the image untouched.
# - A location can have its own `replace_with`, to send that one use elsewhere. Set it to
#   the current image to leave that use untouched (deleted locations come back on re-scan).
# - `helm_paths` come from deployment/helm/values-overrides.yaml (generated by
#   harness-deployment) and show where Helm reads the image; `deployed_as` is the value
#   Helm resolves it to when the file leaves part of it (often the tag) to the chart.
# - Re-running scan keeps every `replace_with` already filled in this file.
#{scope_note}
"""
SCOPE_NOTES = {
    "deployment": """\
# - Scope `deployment` edits the artifacts of harness-deployment, which it overwrites:
#   after every harness-deployment run, run `scan` then `apply` again before deploying.""",
    "sources": """\
# - Scope `sources` edits the CloudHarness sources: after apply, re-run harness-deployment.""",
}


def build_config(root, occs, over, overrides_rel, scope, includes, excludes, previous) -> dict:
    entries = {}
    for o in occs:
        e = entries.setdefault(o.image, {"image": o.image, "replace_with": "", "helm_paths": [], "locations": []})
        e["locations"].append(location_dict(o))

    for ov in over:
        img, hp = ov.image, ov.path
        if img in entries:
            add_unique(entries[img]["helm_paths"], hp)
            continue
        e = match_by_path(entries, occs, ov)
        if e is not None:
            add_unique(e["helm_paths"], hp)
            if strip_tag(e["image"]) == strip_tag(img):
                e["deployed_as"] = img
            continue
        e = entries.setdefault(img, {"image": img, "replace_with": "", "helm_paths": [], "locations": []})
        add_unique(e["helm_paths"], hp)

    prev_entries = {pe.get("image"): pe for pe in (previous or {}).get("images", [])}
    out = []
    for img in sorted(entries):
        e = entries[img]
        pe = prev_entries.get(img)
        if pe:
            e["replace_with"] = pe.get("replace_with") or ""
            prev_locs = {loc_key(pl): pl for pl in pe.get("locations", [])}
            for loc in e["locations"]:
                pl = prev_locs.get(loc_key(loc))
                if pl and pl.get("replace_with"):
                    loc["replace_with"] = pl["replace_with"]
        if not e["helm_paths"]:
            del e["helm_paths"]
        if not e["locations"]:
            e["note"] = f"only listed in {overrides_rel}: no editable use found in scope '{scope}'"
        out.append(e)

    return {
        "root": os.path.abspath(root),
        "generated": datetime.datetime.now().isoformat(timespec="seconds"),
        "values_overrides": overrides_rel if over else None,
        "scope": scope,
        "includes": list(includes),
        "excludes": list(excludes),
        "images": out,
    }


def match_by_path(entries, occs, ov):
    """The entry an override belongs to although its image differs: the same path in the
    generated chart (e.g. values-overrides.yaml older than an apply), or a source leaving the
    tag to the chart (argo `tag: ""`), whose path is a suffix of the helm path."""
    repo = parse_ref(ov.image)["repository"]
    for o in occs:
        if not o.path:
            continue
        if ov.path == o.path or (ov.path.endswith("." + o.path) and parse_ref(o.image)["repository"] == repo):
            return entries[o.image]
    return None


def location_dict(o: Occurrence) -> dict:
    d = {"file": o.file, "line": o.line, "kind": o.kind}
    if o.path:
        d["path"] = o.path
    return d


def loc_key(loc) -> tuple:
    return loc.get("file"), loc.get("kind"), loc.get("path", "")


def add_unique(lst, v):
    if v not in lst:
        lst.append(v)


def write_config(path, config):
    scope = config["scope"]
    with open(path, "w", encoding="utf-8") as f:
        f.write(CONFIG_HEADER.format(config=os.path.basename(path), scope=scope,
                                     scope_note=SCOPE_NOTES[scope][1:]))
        f.write("\n")
        yaml.safe_dump(config, f, sort_keys=False, default_flow_style=False, width=4096, allow_unicode=True)


def load_config(path) -> dict:
    with open(path, encoding="utf-8") as f:
        config = yaml.safe_load(f) or {}
    if not isinstance(config.get("images"), list):
        raise ConfigError(f"{path}: no 'images' list, was it generated by 'scan'?")
    return config


# --------------------------------------------------------------------------- apply

def yaml_token(value: str, style: Optional[str]) -> str:
    if style == "'":
        return "'" + value.replace("'", "''") + "'"
    if style == '"':
        return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'
    try:
        plain_ok = yaml.safe_load(value) == value and not re.search(r": |#|^[@`!&*%|>]", value)
    except yaml.YAMLError:
        plain_ok = False
    return value if plain_ok else "'" + value.replace("'", "''") + "'"


def field_edits(o: Occurrence, new: str) -> list:
    """(line, start, end, text) edits rewriting occurrence `o` to image `new`."""
    roles = [f.role for f in o.fields]
    values = {"full": new} if roles == ["full"] else split_new_image(new, roles)
    edits = []
    for f in o.fields:
        v = values[f.role]
        if v == f.value:
            continue
        is_yaml_scalar = o.kind in ("yaml", "yaml-split")
        if f.insert_at is not None:
            edits.append((f.line, f.insert_at, f.insert_at, " " + yaml_token(v, None)))
        elif is_yaml_scalar:
            edits.append((f.line, f.start, f.end, yaml_token(v, f.style)))
        else:
            edits.append((f.line, f.start, f.end, v))
    return edits


def find_occurrence(by_file, loc, image, used):
    candidates = [
        o for o in by_file.get(loc.get("file"), [])
        if o.image == image and o.kind == loc.get("kind")
        and (not loc.get("path") or o.path == loc.get("path")) and id(o) not in used
    ]
    if not candidates:
        return None
    return min(candidates, key=lambda o: abs(o.line - int(loc.get("line") or 0)))


def apply(root, config, dry_run) -> int:
    scope = config.get("scope") or "deployment"
    includes = config.get("includes") or SCOPES[scope]["includes"]
    excludes = config.get("excludes") or SCOPES[scope]["excludes"]
    known = set()
    for entry in config["images"]:
        known.add(entry.get("image"))
        known.add(entry.get("replace_with"))
        known.update(loc.get("replace_with") for loc in entry.get("locations") or [])
    known = {k.strip() for k in known if isinstance(k, str) and k.strip()}
    occs = scan(root, includes, excludes, known, built_images(root, known))
    by_file = {}
    for o in occs:
        by_file.setdefault(o.file, []).append(o)

    edits_by_file = {}
    used = set()
    changed = skipped = already = 0
    problems = []

    for entry in config["images"]:
        image = entry.get("image")
        for loc in entry.get("locations") or []:
            new = (loc.get("replace_with") or entry.get("replace_with") or "").strip()
            if not new or new == image:
                continue
            where = f"{loc.get('file')}:{loc.get('line')}"
            if not is_image(new):
                problems.append(f"{where}: '{new}' is not a valid image reference, skipped")
                skipped += 1
                continue
            o = find_occurrence(by_file, loc, image, used)
            if o is None:
                if find_occurrence(by_file, loc, new, used):
                    already += 1
                else:
                    problems.append(f"{where}: '{image}' not found any more ({loc.get('kind')} "
                                    f"{loc.get('path', '')}), re-run scan")
                    skipped += 1
                continue
            try:
                edits = field_edits(o, new)
            except ConfigError as e:
                problems.append(f"{where}: {e}, skipped")
                skipped += 1
                continue
            used.add(id(o))
            edits_by_file.setdefault(o.file, []).extend(edits)
            changed += 1
            print(f"  {o.file}:{o.line}  {image}  ->  {new}")

    for rel, edits in sorted(edits_by_file.items()):
        lines = read_lines(root, rel)
        new_lines = list(lines)
        for line, start, end, text in sorted(set(edits), key=lambda e: (e[0], -e[1])):
            s = new_lines[line]
            new_lines[line] = s[:start] + text + s[end:]
        if dry_run:
            sys.stdout.writelines(difflib.unified_diff(
                [l + "\n" for l in lines], [l + "\n" for l in new_lines],
                fromfile=f"a/{rel}", tofile=f"b/{rel}"))
        else:
            with open(os.path.join(root, rel), "w", encoding="utf-8", errors="surrogateescape") as f:
                f.write("\n".join(new_lines))

    for p in problems:
        print(f"WARNING {p}", file=sys.stderr)
    verb = "would change" if dry_run else "changed"
    print(f"\n{verb} {changed} location(s) in {len(edits_by_file)} file(s); "
          f"{already} already up to date; {skipped} skipped")
    if changed and not dry_run:
        if scope == "deployment":
            print("harness-deployment overwrites these files: after regenerating, run scan then apply again.")
        else:
            print("Re-run harness-deployment to regenerate the deployment files, then re-run scan.")
    return 1 if problems else 0


