def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="mode")
    raw = argparse.RawDescriptionHelpFormatter

    s = sub.add_parser("scan", help="list every image in a configuration file", formatter_class=raw,
                       epilog="examples:\n"
                              "  python ch_images.py scan\n"
                              "  python ch_images.py scan --root ~/cloud-harness --config ~/mirror.yaml\n"
                              "  python ch_images.py scan --scope sources --exclude 'applications/samples/*'\n"
                              "\nrun `python ch_images.py help` for the full guide")
    s.add_argument("--root", default=".", help="CloudHarness checkout (default: current directory)")
    s.add_argument("--scope", choices=sorted(SCOPES), default="deployment",
                   help="deployment: harness-deployment artifacts + Dockerfiles (default); "
                        "sources: the CloudHarness sources")
    s.add_argument("--config", default=DEFAULT_CONFIG, help="configuration file to write (default: ch-images.yaml next to this script)")
    s.add_argument("--overrides", default=OVERRIDES_FILE,
                   help=f"values-overrides.yaml, relative to root (default: {OVERRIDES_FILE})")
    s.add_argument("--include-tests", action="store_true", help="also scan test fixtures (*/tests/*, */test/resources/*)")
    s.add_argument("--exclude", action="append", default=[], metavar="GLOB",
                   help="extra path glob to skip, relative to root (repeatable)")
    s.add_argument("--fresh", action="store_true", help="discard replace_with values of an existing config")

    a = sub.add_parser("apply", help="replace images whose replace_with is filled", formatter_class=raw,
                       epilog="examples:\n"
                              "  python ch_images.py apply --dry-run\n"
                              "  python ch_images.py apply --config ~/mirror.yaml\n"
                              "\nrun `python ch_images.py help` for the full guide")
    a.add_argument("--root", help="CloudHarness checkout (default: the root recorded in the config)")
    a.add_argument("--config", default=DEFAULT_CONFIG, help="configuration file to read (default: ch-images.yaml next to this script)")
    a.add_argument("--dry-run", action="store_true", help="print a diff instead of writing files")

    sub.add_parser("help", help="full guide: workflow, configuration format, tips")

    args = ap.parse_args(argv)
    if args.mode in (None, "help"):
        print(GUIDE)
        return 0
    try:
        if args.mode == "scan":
            root = os.path.abspath(args.root)
            includes = SCOPES[args.scope]["includes"]
            excludes = SCOPES[args.scope]["excludes"] + ([] if args.include_tests else TEST_EXCLUDES) + args.exclude
            for own in (os.path.abspath(args.config), os.path.dirname(os.path.abspath(__file__))):
                own_rel = os.path.relpath(own, root).replace(os.sep, "/")
                if not own_rel.startswith(".."):
                    excludes.append(own_rel if own.endswith((".yaml", ".yml")) else own_rel + "/*")
            previous = None
            if os.path.isfile(args.config) and not args.fresh:
                previous = load_config(args.config)
            over = overrides_images(root, args.overrides)
            pulled = {o.image for o in over}
            occs = scan(root, includes, excludes, pulled, built_images(root, pulled))
            config = build_config(root, occs, over, args.overrides, args.scope, includes, excludes, previous)
            if over and args.scope == "sources" and overrides_stale(root, args.overrides, occs):
                print(f"WARNING {args.overrides} is older than the sources: re-run harness-deployment "
                      "for up to date helm paths", file=sys.stderr)
            write_config(args.config, config)
            n_loc = sum(len(e["locations"]) for e in config["images"])
            src = f", helm paths from {args.overrides}" if config["values_overrides"] else \
                f" ({args.overrides} not found: run harness-deployment to get helm paths)"
            print(f"scope {args.scope}: {len(config['images'])} images, {n_loc} locations{src}\n"
                  f"written to {args.config}")
            return 0
        config = load_config(args.config)
        root = os.path.abspath(args.root or config.get("root") or ".")
        return apply(root, config, args.dry_run)
    except ConfigError as e:
        print(f"ERROR {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
